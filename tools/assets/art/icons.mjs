/** Builds a 16x16 icon and validates its size. */
function icon(name, rows, { outline = true } = {}) {
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) {
    throw new Error(`icon ${name}: must be 16 rows of 16 characters`);
  }
  const c = new Canvas(16, 16);
  c.ascii(rows, LEGEND);
  if (outline) c.outline(P.outline);
  return { name, canvas: c };
}

