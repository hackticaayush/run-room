export function buildCursors() {
  const legend = { o: P.outline, W: P.white, C: P.cyan2 };
  const make = (rows) => {
    const c = new Canvas(16, 16);
    c.ascii(rows, legend);
    return c;
  };
  return [
    { name: 'cursor_arrow', canvas: make(CURSOR_ARROW), hotspot: { x: 0, y: 0 } },
    { name: 'cursor_hand', canvas: make(CURSOR_HAND), hotspot: { x: 5, y: 0 } },
  ];
}
