/** Badge digits: 5x7 glyphs in yellow with a 1px outline (7x9 sprites). */
export function buildDigits() {
  const out = [];
  for (let d = 0; d <= 9; d++) {
    const c = new Canvas(7, 9);
    const rows = FONT5.glyphs.get(String(d));
    rows.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') c.px(x + 1, y + 1, y < 2 ? P.yel3 : P.yel2);
    });
    c.outline(P.outline, { diagonal: true });
    out.push({ name: `digit_${d}`, canvas: c });
  }
  return out;
}

