function compile(table, w, h, name) {
  const glyphs = new Map();
  for (const [ch, spec] of Object.entries(table)) {
    const rows = spec.split(' ');
    if (rows.length !== h || rows.some((r) => r.length !== w)) {
      throw new Error(`font ${name}: glyph "${ch}" is not ${w}x${h}`);
    }
    glyphs.set(ch, rows);
  }
  return { name, w, h, advance: w + 1, lineHeight: h + 2, glyphs };
}

export const FONT5 = compile(G5, 5, 7, 'ghost5x7');
export const FONT3 = compile(G3, 3, 5, 'ghost3x5');

function glyphFor(font, ch) {
  return font.glyphs.get(ch) ?? font.glyphs.get(ch.toUpperCase()) ?? font.glyphs.get('?');
}

export function textWidth(text, font = FONT5, scale = 1) {
  if (!text.length) return 0;
  return (text.length * font.advance - 1) * scale;
}

/** Draws text with the pixel font at an integer scale. */
export function drawText(canvas, text, x, y, color = P.white, font = FONT5, scale = 1) {
  let cx = x;
  for (const ch of text) {
    const rows = glyphFor(font, ch);
    for (let gy = 0; gy < font.h; gy++) {
      for (let gx = 0; gx < font.w; gx++) {
        if (rows[gy][gx] !== '#') continue;
        canvas.rect(cx + gx * scale, y + gy * scale, scale, scale, color);
      }
    }
    cx += font.advance * scale;
  }
  return cx - x;
}

/** Draws text with a 1px outline (useful on busy backgrounds). */
export function drawTextOutlined(canvas, text, x, y, color, outline, font = FONT5, scale = 1) {
  const tmp = new Canvas(textWidth(text, font, scale) + 2, font.h * scale + 2);
  drawText(tmp, text, 1, 1, color, font, scale);
  tmp.outline(outline, { diagonal: true });
  canvas.blit(tmp, x - 1, y - 1);
}

/**
 * Exports a font as a PNG strip + AngelCode BMFont XML that Phaser loads with
 * this.load.bitmapFont(key, png, xml). Upper case glyphs are reused for lower case letters.
 */
export function buildBitmapFont(font, imageFile) {
  const chars = [...font.glyphs.keys()];
  const cols = 16;
  const cellW = font.w + 1;
  const cellH = font.h + 1;
  const rows = Math.ceil(chars.length / cols);
  const canvas = new Canvas(cols * cellW, rows * cellH);
  const entries = [];
  chars.forEach((ch, i) => {
    const x = (i % cols) * cellW;
    const y = Math.floor(i / cols) * cellH;
    drawText(canvas, ch, x, y, P.white, font, 1);
    entries.push({ code: ch.charCodeAt(0), x, y });
    if (ch >= 'A' && ch <= 'Z') entries.push({ code: ch.toLowerCase().charCodeAt(0), x, y });
  });
  entries.sort((a, b) => a.code - b.code);
  const lines = [
    '<?xml version="1.0"?>',
    '<font>',
    `  <info face="${font.name}" size="${font.h}" bold="0" italic="0" charset="" unicode="0" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="1,1"/>`,
    `  <common lineHeight="${font.lineHeight}" base="${font.h}" scaleW="${canvas.w}" scaleH="${canvas.h}" pages="1" packed="0"/>`,
    '  <pages>',
    `    <page id="0" file="${imageFile}"/>`,
    '  </pages>',
    `  <chars count="${entries.length}">`,
    ...entries.map(
      (e) =>
        `    <char id="${e.code}" x="${e.x}" y="${e.y}" width="${font.w}" height="${font.h}" xoffset="0" yoffset="0" xadvance="${font.advance}" page="0" chnl="15"/>`,
    ),
    '  </chars>',
    '</font>',
    '',
  ];
  return { canvas, xml: lines.join('\n') };
}
