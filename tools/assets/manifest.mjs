// Writes client/src/assets/manifest.ts: the ONLY place game code and React look up asset names.

import { join } from 'node:path';
import { REPO_ROOT, writeText } from './lib/io.mjs';
import { P } from './lib/palette.mjs';

const MANIFEST = join(REPO_ROOT, 'client', 'src', 'assets', 'manifest.ts');
const PALETTE_CSS = join(REPO_ROOT, 'client', 'src', 'styles', 'palette.generated.css');

/** The HUD uses the same palette as the sprites, exposed as CSS custom properties. */
export function writePaletteCss() {
  const lines = ['/* GENERATED by tools/assets/generate.mjs from tools/assets/lib/palette.mjs - do not edit. */', ':root {'];
  for (const [name, value] of Object.entries(P)) {
    if (!value) continue;
    const css = name.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();
    lines.push(`  --c-${css}: ${value};`);
  }
  lines.push('}', '');
  writeText(PALETTE_CSS, lines.join('\n'));
}

function rects(frames) {
  const out = {};
  for (const [name, r] of Object.entries(frames)) out[name] = { x: r.x, y: r.y, w: r.w, h: r.h };
  return out;
}

const json = (v) => JSON.stringify(v, null, 2);

export function writeManifest({ tileset, props, fx, uiIcons, moods, characters, chrome, portraits, cursors, fonts, sheets, moodNames, emissive }) {
  const atlas = (key, a) => ({
    key,
    image: a.json.meta.image,
    json: a.json.meta.image.replace('.png', '.json'),
    width: a.canvas.w,
    height: a.canvas.h,
    frames: rects(a.frames),
  });

  const chromeEntries = {};
  for (const c of chrome) {
    chromeEntries[c.name] = { image: `ui/${c.name}.png`, width: c.canvas.w, height: c.canvas.h, slice: c.slice };
  }
  const moodMap = {};
  for (const m of moodNames) moodMap[m] = `mood_${m}`;

  const ts = `// GENERATED by tools/assets/generate.mjs - do not edit by hand (run: npm run assets).
// The ONLY place game code and React components look up asset names and frame rectangles.
// To swap in your own art, drop art/overrides/<group>/<name>.png files and re-run the generator,
// or replace the PNG + JSON pairs in client/public/assets and update this file to match.

export const ASSET_BASE = '/assets/';

/** Absolute URL of a file inside client/public/assets. */
export function assetUrl(file: string): string {
  return ASSET_BASE + file;
}

export interface FrameRect {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}

export interface AtlasInfo {
  readonly key: string;
  readonly image: string;
  readonly json: string;
  readonly width: number;
  readonly height: number;
  readonly frames: Readonly<Record<string, FrameRect>>;
}

export interface SliceInfo {
  readonly top: number;
  readonly right: number;
  readonly bottom: number;
  readonly left: number;
}

export const TILESET = ${json({ key: 'tiles', image: 'tileset.png', json: 'tileset.json', tileSize: 16, columns: tileset.columns, tiles: tileset.index })} as const;
export type TileName = keyof typeof TILESET.tiles;

export const PROPS = ${json(atlas('props', props))} as const satisfies AtlasInfo;
export type PropName = keyof typeof PROPS.frames;

export const FX = ${json(atlas('fx', fx))} as const satisfies AtlasInfo;
export type FxName = keyof typeof FX.frames;

export const UI_ICONS = ${json(atlas('ui_icons', uiIcons))} as const satisfies AtlasInfo;
export type IconName = keyof typeof UI_ICONS.frames;

export const MOODS = ${json(atlas('moods', moods))} as const satisfies AtlasInfo;
export type MoodFaceName = keyof typeof MOODS.frames;

/** Mood id (as used by the simulation) -> mood face sprite in the MOODS atlas. */
export const MOOD_FACES = ${json(moodMap)} as const;

/** Badge digit sprites (in UI_ICONS), index = digit. */
export const DIGITS = ${json([...Array(10).keys()].map((d) => `digit_${d}`))} as const;

export const CHARACTERS = ${json({
    json: 'characters.json',
    frameWidth: characters.frameWidth,
    frameHeight: characters.frameHeight,
    columns: characters.columns,
    rows: characters.rows,
    sheets: { ghost: 'ghost.png', byte: 'byte.png' },
    animations: characters.animations,
  })} as const;
export type CharacterKey = keyof typeof CHARACTERS.sheets;
export type CharacterAnim = keyof typeof CHARACTERS.animations;

/** 9-slice UI chrome. slice = margins in source pixels (also in ui/ui_chrome.json). */
export const CHROME = ${json(chromeEntries)} as const;
export type ChromeName = keyof typeof CHROME;

export const PORTRAITS = ${json(portraits)} as const;
export type PortraitKey = keyof typeof PORTRAITS;

/** CSS cursors are separate files (drawn at 16x16, written at 2x). */
export const CURSORS = ${json(cursors)} as const;

/** Bitmap fonts drawn by the generator, used inside the Phaser canvas (bubbles, tickers). */
export const BITMAP_FONTS = ${json(fonts)} as const;

/** Contact sheets and the preview render, shown on /assets-test. */
export const SHEETS = ${json(sheets)} as const;

/**
 * Night lighting: copies of the art that keep only light emitting pixels (same frame layout).
 * At night every sprite is tinted with nightTint and its emissive copy is drawn just above it.
 */
export const EMISSIVE = ${json(emissive)} as const;
`;
  writeText(MANIFEST, ts);
  return MANIFEST;
}
